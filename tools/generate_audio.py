#!/usr/bin/env python3
"""Procedurally synthesises every LUMA sound effect and the ambient music loop.

All audio in assets/audio is generated by this script (original work, no
samples), so it is fully redistributable. Deterministic: same output each run.

    python3 tools/generate_audio.py            # writes assets/audio/**.wav
"""
import os
import wave

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SFX_DIR = os.path.join(ROOT, "assets", "audio", "sfx")
MUSIC_DIR = os.path.join(ROOT, "assets", "audio", "music")
SR = 44100
rng = np.random.default_rng(20261025)


def t_axis(dur, sr=SR):
    return np.arange(int(dur * sr)) / sr


def env(n, attack, release, sr=SR, curve=4.0):
    a = max(1, int(attack * sr))
    e = np.ones(n)
    e[:a] = np.linspace(0, 1, a)
    tail = np.linspace(0, 1, n - a)
    e[a:] = np.exp(-curve * tail * (n - a) / max(1, release * sr))
    return e


def bell(freq, dur, sr=SR, bright=1.0):
    t = t_axis(dur, sr)
    partials = [(1.0, 1.0), (2.0, 0.35 * bright), (3.01, 0.18 * bright), (4.2, 0.08 * bright)]
    s = sum(a * np.sin(2 * np.pi * freq * m * t) * np.exp(-t * (2.5 + m * 1.5)) for m, a in partials)
    return s * env(len(t), 0.004, dur, sr, 1.0)


def pluck(freq, dur, sr=SR):
    t = t_axis(dur, sr)
    s = np.sin(2 * np.pi * freq * t) + 0.3 * np.sin(2 * np.pi * freq * 2 * t) + 0.12 * np.sin(2 * np.pi * freq * 3 * t)
    return s * np.exp(-t * 5.0) * env(len(t), 0.003, dur, sr, 0.5)


def noise(dur, sr=SR):
    return rng.standard_normal(int(dur * sr))


def lowpass(x, cutoff, sr=SR):
    # one-pole low-pass; good enough for soft textures
    a = np.exp(-2 * np.pi * cutoff / sr)
    y = np.zeros_like(x)
    acc = 0.0
    for i, v in enumerate(x):
        acc = (1 - a) * v + a * acc
        y[i] = acc
    return y


def place(buf, clip, at, sr=SR):
    i = int(at * sr)
    j = min(len(buf), i + len(clip))
    buf[i:j] += clip[: j - i]


def norm(x, peak=0.8):
    m = np.max(np.abs(x)) or 1.0
    return x / m * peak


def write(path, x, sr=SR):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    data = (np.clip(x, -1, 1) * 32767).astype("<i2")
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(sr)
        w.writeframes(data.tobytes())
    print("wrote", os.path.relpath(path, ROOT), f"{len(x) / sr:.2f}s")


def note(n):
    """MIDI note number -> Hz"""
    return 440.0 * 2 ** ((n - 69) / 12)


def sfx():
    # tap: wooden knock
    t = t_axis(0.09)
    knock = np.sin(2 * np.pi * 820 * t) * np.exp(-t * 60) + 0.5 * np.sin(2 * np.pi * 1640 * t) * np.exp(-t * 90)
    knock += lowpass(noise(0.09), 3000) * np.exp(-t * 120) * 0.6
    write(os.path.join(SFX_DIR, "tap.wav"), norm(knock, 0.55))

    # rotate: soft stone slide + settle click
    d = 0.16
    t = t_axis(d)
    slide = lowpass(noise(d), 1400) * np.sin(np.pi * t / d) ** 2 * 0.8
    click = np.zeros_like(t)
    place(click, np.sin(2 * np.pi * 520 * t_axis(0.05)) * np.exp(-t_axis(0.05) * 70), 0.11)
    write(os.path.join(SFX_DIR, "rotate.wav"), norm(slide + click, 0.5))

    # toggle: lever clunk
    t = t_axis(0.2)
    clunk = (np.sin(2 * np.pi * 180 * t) + 0.6 * np.sign(np.sin(2 * np.pi * 270 * t)) * 0.3) * np.exp(-t * 25)
    clunk += lowpass(noise(0.2), 800) * np.exp(-t * 40) * 0.7
    write(os.path.join(SFX_DIR, "toggle.wav"), norm(clunk, 0.6))

    # flow: bubbling water
    d = 0.9
    buf = lowpass(noise(d), 700) * 0.25 * np.sin(np.pi * t_axis(d) / d)
    for k in range(18):
        f = rng.uniform(380, 950)
        bd = rng.uniform(0.04, 0.09)
        bt = t_axis(bd)
        blip = np.sin(2 * np.pi * (f + 900 * bt) * bt) * np.exp(-bt * 45)
        place(buf, blip * rng.uniform(0.3, 0.7), rng.uniform(0, d - bd))
    write(os.path.join(SFX_DIR, "flow.wav"), norm(buf, 0.45))

    # connect: two soft bells
    buf = np.zeros(int(0.9 * SR))
    place(buf, bell(note(76), 0.8), 0.0)
    place(buf, bell(note(83), 0.8) * 0.8, 0.09)
    write(os.path.join(SFX_DIR, "connect.wav"), norm(buf, 0.5))

    # bloom: rising sparkle arpeggio
    buf = np.zeros(int(1.3 * SR))
    for i, n in enumerate([84, 88, 91, 96]):
        place(buf, bell(note(n), 0.9, bright=0.6) * (0.9 - i * 0.12), i * 0.07)
    write(os.path.join(SFX_DIR, "bloom.wav"), norm(buf, 0.45))

    # complete: pentatonic cascade over a warm pad
    d = 2.4
    buf = np.zeros(int(d * SR))
    t = t_axis(d)
    pad = sum(np.sin(2 * np.pi * note(n) * t) for n in [60, 64, 67, 71]) * env(len(t), 0.25, 2.0, curve=2.0) * 0.18
    buf += pad
    for i, n in enumerate([72, 74, 76, 79, 81, 84]):
        place(buf, pluck(note(n), 1.0) * 0.6, 0.05 + i * 0.09)
    place(buf, bell(note(88), 1.5) * 0.4, 0.62)
    write(os.path.join(SFX_DIR, "complete.wav"), norm(buf, 0.6))

    # unlock: shimmering glissando + chord
    d = 1.8
    t = t_axis(d)
    gl = np.sin(2 * np.pi * (400 * t + 500 * t * t)) * env(len(t), 0.05, 0.6, curve=3.0) * 0.3
    buf = gl.copy()
    for i, n in enumerate([67, 71, 74, 79]):
        place(buf, bell(note(n), 1.3, bright=0.7) * 0.5, 0.35 + i * 0.05)
    write(os.path.join(SFX_DIR, "unlock.wav"), norm(buf, 0.55))

    # ui click / back / hint / leak
    t = t_axis(0.05)
    write(os.path.join(SFX_DIR, "ui_click.wav"), norm(np.sin(2 * np.pi * 1300 * t) * np.exp(-t * 110), 0.35))
    write(os.path.join(SFX_DIR, "ui_back.wav"), norm(np.sin(2 * np.pi * 700 * t) * np.exp(-t * 90), 0.35))
    buf = np.zeros(int(0.7 * SR))
    place(buf, bell(note(81), 0.6, bright=0.4), 0.0)
    place(buf, bell(note(86), 0.6, bright=0.4) * 0.7, 0.12)
    write(os.path.join(SFX_DIR, "hint.wav"), norm(buf, 0.4))
    d = 0.35
    t = t_axis(d)
    drip = np.sin(2 * np.pi * (1200 - 1500 * t) * t) * np.exp(-t * 18)
    write(os.path.join(SFX_DIR, "drip.wav"), norm(drip, 0.3))


def music():
    """48 s seamless ambient loop: slow pad progression + sparse marimba."""
    sr = 22050
    bars = [[48, 55, 64, 71], [45, 52, 60, 67], [41, 48, 57, 64], [43, 50, 59, 62]]  # Cmaj7 Am7 Fmaj7 G6
    seg = 12.0
    total = seg * len(bars)
    n = int(total * sr)
    buf = np.zeros(n)
    t_seg = t_axis(seg + 4.0, sr)
    for i, chord in enumerate(bars):
        pad = np.zeros_like(t_seg)
        for k, m in enumerate(chord):
            f = note(m)
            # gentle detuned pair for warmth + slow tremolo
            pad += (np.sin(2 * np.pi * f * t_seg) + np.sin(2 * np.pi * f * 1.003 * t_seg)) * (0.5 if k else 0.7)
        pad *= 0.6 + 0.4 * np.sin(2 * np.pi * 0.1 * t_seg + i)
        shape = np.minimum(1.0, t_seg / 3.0) * np.minimum(1.0, np.maximum(0.0, (seg + 4.0 - t_seg) / 4.0))
        clip = pad * shape * 0.08
        start = int(i * seg * sr)
        for j in range(len(clip)):
            buf[(start + j) % n] += clip[j]  # wraps tail to loop start -> seamless
    pent = [72, 74, 76, 79, 81, 84]
    local = np.random.default_rng(7)
    tt = 0.5
    while tt < total - 0.1:
        chord = bars[int(tt // seg)]
        choices = [p for p in pent if (p % 12) in [c % 12 for c in chord]] or pent
        m = choices[local.integers(len(choices))]
        clip = pluck(note(m), 1.6, sr) * local.uniform(0.08, 0.16)
        s = int(tt * sr)
        for j in range(len(clip)):
            buf[(s + j) % n] += clip[j]
        tt += local.choice([1.5, 2.0, 3.0, 4.0])
    write(os.path.join(MUSIC_DIR, "verdant_ambience.wav"), norm(buf, 0.5), sr)


if __name__ == "__main__":
    sfx()
    music()
